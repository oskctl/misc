// Packs drawings into data/drawings.js, then bundles the game into single-file pages:
//   dist/markle.html    a complete standalone page you can host anywhere
//   dist/artifact.html  the same page without <html>/<head>/<body>, for claude.ai Artifacts
// Usage: node tools/build.mjs [--pack-only]
import { readFileSync, writeFileSync, readdirSync, mkdirSync } from 'node:fs';
import { resolve, dirname, basename } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const args = process.argv.slice(2);
if (args.includes('--help')) {
  console.log('usage: node tools/build.mjs [--pack-only]');
  process.exit(0);
}

export function packDrawings() {
  const dir = resolve(root, 'drawings');
  const files = readdirSync(dir).filter(f => f.endsWith('.svg')).sort();
  const entries = files.map(f => {
    const svg = readFileSync(resolve(dir, f), 'utf8')
      .replace(/<\?xml[^>]*>\s*/, '').replace(/<!--[\s\S]*?-->/g, '')
      .replace(/>\s+</g, '><').replace(/\s{2,}/g, ' ').trim();
    return `  ${JSON.stringify(basename(f, '.svg'))}: ${JSON.stringify(svg)},`;
  });
  writeFileSync(resolve(root, 'data/drawings.js'),
    `// Generated by tools/build.mjs from drawings/*.svg. Do not edit by hand.\nexport const DRAWINGS = {\n${entries.join('\n')}\n};\n`);
  console.log(`  Packed ${files.length} drawing(s) into data/drawings.js`);
}

packDrawings();
if (args.includes('--pack-only')) process.exit(0);

const { build } = await import('esbuild');
const bundle = await build({
  entryPoints: [resolve(root, 'src/app.js')],
  bundle: true, format: 'iife', minify: true, write: false, target: 'es2020',
  legalComments: 'none',
});
const js = bundle.outputFiles[0].text.replace(/<\/script/gi, '<\\/script');

let html = readFileSync(resolve(root, 'index.html'), 'utf8');
html = html.replace(/<link rel="stylesheet" href="(styles\/[^"]+)">/g, (_, href) =>
  `<style>\n${readFileSync(resolve(root, href), 'utf8')}</style>`);
html = html.replace(/<script type="module" src="src\/app\.js"><\/script>/, () => `<script>${js}</script>`);
if (/src="src\//.test(html) || /href="styles\//.test(html)) throw new Error('unbundled reference left in index.html');

mkdirSync(resolve(root, 'dist'), { recursive: true });
writeFileSync(resolve(root, 'dist/markle.html'), html);

// The Artifact host wraps the page in its own document skeleton.
const head = html.match(/<head>([\s\S]*?)<\/head>/)[1]
  .replace(/<meta charset[^>]*>\s*/i, '').replace(/<meta name="viewport"[^>]*>\s*/i, '');
const body = html.match(/<body[^>]*>([\s\S]*?)<\/body>/)[1];
writeFileSync(resolve(root, 'dist/artifact.html'), `${head.trim()}\n${body.trim()}\n`);

const kb = n => `${(Buffer.byteLength(n) / 1024).toFixed(0)} KB`;
console.log(`  Wrote dist/markle.html (${kb(html)}) and dist/artifact.html`);
