// Projects Natural Earth 110m land (world-atlas) with Equal Earth and writes a JS module
// exporting the SVG path plus the projection constants the game needs to place points.
import { readFileSync, writeFileSync } from 'node:fs';
import { feature } from 'topojson-client';
import { geoEqualEarth, geoPath } from 'd3-geo';
const W = 1000, H = 487;
const topo = JSON.parse(readFileSync(new URL('./node_modules/world-atlas/land-110m.json', import.meta.url)));
let land = feature(topo, topo.objects.land);
// drop Antarctica: it eats a third of the frame and holds no buildings
land = { ...land, features: land.features.map(f => ({ ...f, geometry: { ...f.geometry,
  coordinates: f.geometry.coordinates.filter(poly => Math.max(...poly[0].map(p => p[1])) > -60) } })) };
const proj = geoEqualEarth().fitExtent([[4, 4], [W - 4, H - 4]], land);
const d = geoPath(proj).digits(1)(land);
console.log('scale', proj.scale(), 'translate', proj.translate(), 'bytes', d.length);
writeFileSync(process.argv[2] || 'worldmap.js',
`// Generated by tools/build-map.mjs from Natural Earth 110m land (public domain) via world-atlas.\n` +
`// Equal Earth projection; Antarctica removed.\n` +
`export const MAP = { width: ${W}, height: ${H}, scale: ${proj.scale().toFixed(4)}, translate: [${proj.translate().map(v => v.toFixed(4)).join(', ')}] };\n` +
`export const LAND_PATH = "${d}";\n`);
